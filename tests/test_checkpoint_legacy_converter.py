def test_independent_validator_rejects_hostile_worker_output(tmp_path, monkeypatch):
    module = converter()
    path, output, digest = legacy(tmp_path)
    marker = tmp_path / "validator-executed"
    class Exploit:
        def __reduce__(self):
            return os.system, ("touch " + str(marker),)
    original = module._sandbox_command
    def tamper(settings, descriptors, *, validation):
        if validation:
            manifest = output / "checkpoint.manifest.json"
            record = json.loads(manifest.read_text())
            artifact = output / record["artifact_path"]
            torch.save({"model_state_dict": {"evil": Exploit()}, "iteration": 2}, artifact)
            record.update(byte_size=artifact.stat().st_size, sha256=hashlib.sha256(artifact.read_bytes()).hexdigest())
            manifest.write_text(json.dumps(record))
        return original(settings, descriptors, validation=validation)
    monkeypatch.setattr(module, "_sandbox_command", tamper)
    with pytest.raises(ValueError, match="safe validator"):
        convert(module, path, output, digest)
    assert not marker.exists()
    assert not (output / "conversion-receipt.json").exists()


@pytest.mark.parametrize("kind", ["input", "output"])
def test_converter_rejects_symlink_targets(tmp_path, kind):
    module = converter()
    path, output, digest = legacy(tmp_path)
    link = tmp_path / "link"
    link.symlink_to(path if kind == "input" else output, target_is_directory=kind == "output")
    with pytest.raises(ValueError):
        convert(module, link if kind == "input" else path, link if kind == "output" else output, digest)
    assert not list(output.iterdir())


def test_approved_input_snapshot_is_stable_under_in_place_host_write(tmp_path, monkeypatch):
    module = converter()
    path, output, digest = legacy(tmp_path)
    old_inode = path.stat().st_ino
    original = module._sandbox_command
    def mutate(settings, descriptors, *, validation):
        if not validation:
            with path.open("r+b") as handle:
                handle.write(b"X" * path.stat().st_size)
            assert path.stat().st_ino == old_inode
        return original(settings, descriptors, validation=validation)
    monkeypatch.setattr(module, "_sandbox_command", mutate)
    receipt = convert(module, path, output, digest)
    assert receipt["input_sha256"] == digest and receipt["iteration"] == 2
