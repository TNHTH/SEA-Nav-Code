def test_actual_untrusted_probe_cannot_see_host_credentials_or_network(tmp_path, monkeypatch):
    monkeypatch.setenv("SEA_NAV_TEST_CREDENTIAL", "fixture-only-do-not-inherit")
    module = converter()
    class Probe:
        def __reduce__(self):
            code = "{'home':__import__('os').path.exists('/home'),'credential':__import__('os').environ.get('SEA_NAV_TEST_CREDENTIAL'),'interfaces':[n for i,n in __import__('socket').if_nameindex()]}"
            return eval, (code,)
    path, output, _ = legacy(tmp_path)
    torch.save({"model_state_dict": {"probe": Probe()}, "iter": 0}, path)
    receipt = convert(module, path, output, hashlib.sha256(path.read_bytes()).hexdigest())
    from rsl_rl.utils.checkpoint import load_checkpoint_v2
    probe = load_checkpoint_v2(output / "checkpoint.manifest.json", artifact_root=output).model_state_dict["probe"]
    assert probe == {"home": False, "credential": None, "interfaces": ["lo"]}
    assert receipt["resource_limits"]["memory_bytes"] == 4 * 1024**3


def test_pinned_input_survives_pathname_swap_before_sandbox(tmp_path, monkeypatch):
    module = converter()
    path, output, digest = legacy(tmp_path)
    original = module._sandbox_command
    def swap(settings, descriptors, *, validation):
        if not validation:
            path.rename(tmp_path / "retained-original")
            path.write_bytes(b"replacement path is not the approved input")
        return original(settings, descriptors, validation=validation)
    monkeypatch.setattr(module, "_sandbox_command", swap)
    assert convert(module, path, output, digest)["input_sha256"] == digest


def test_untrusted_infinite_work_is_terminated_without_receipt(tmp_path):
    module = converter()
