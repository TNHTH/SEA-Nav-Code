import hashlib
import importlib.util
import json
import os
from pathlib import Path

import pytest
import torch

from test_checkpoint_v2 import COMMIT, CONFIG, adam_fixture
from test_runtime_cli_contract import ROOT


def converter():
    path = ROOT / "tools/convert_legacy_checkpoint.py"
    spec = importlib.util.spec_from_file_location("operator_converter", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def legacy(tmp_path):
    model, optimizer = adam_fixture()
    path = tmp_path / "legacy.pt"
    torch.save(dict(model_state_dict=model.state_dict(), optimizer_state_dict=optimizer.state_dict(), iter=2), path)
    output = tmp_path / "output"
    output.mkdir()
    return path, output, hashlib.sha256(path.read_bytes()).hexdigest()


def convert(module, path, output, digest, **kwargs):
    return module.convert_legacy_checkpoint_once(path, output_root=output, approved_sha256=digest,
        producer_commit=COMMIT, resolved_config_sha256=CONFIG, **kwargs)


def test_operator_hash_empty_output_and_isolation_fail_closed(tmp_path, monkeypatch):
    module = converter()
    path, output, digest = legacy(tmp_path)
    with pytest.raises(ValueError, match="SHA"):
        convert(module, path, output, "f" * 64)
    assert not list(output.iterdir())
    (output / "existing").write_text("preserve")
    with pytest.raises(ValueError, match="empty"):
        convert(module, path, output, digest)
    assert (output / "existing").read_text() == "preserve"
    empty = tmp_path / "empty"
    empty.mkdir()
    monkeypatch.setattr(module, "BWRAP", "/missing/bwrap")
    with pytest.raises(ValueError, match="blocked"):
        convert(module, path, empty, digest)
    assert not list(empty.iterdir())


def test_real_os_sandbox_converts_and_external_loader_accepts(tmp_path):
    module = converter()
    path, output, digest = legacy(tmp_path)
    receipt = convert(module, path, output, digest)
    assert receipt["input_sha256"] == digest
    assert receipt["independent_safe_validation"] is True
    assert receipt["isolation"] == "bubblewrap-unshare-all"
    from rsl_rl.utils.checkpoint import load_checkpoint_v2
    loaded = load_checkpoint_v2(output / "checkpoint.manifest.json", artifact_root=output)
    assert loaded.iteration == 2
    assert loaded.optimizer_state_dict["state"]
    assert receipt["output_manifest_sha256"] == loaded.manifest_sha256
    assert json.loads((output / "conversion-receipt.json").read_text()) == receipt


def test_malicious_legacy_has_no_host_side_effect(tmp_path):
    module = converter()
    marker = tmp_path / "host-side-effect"
    class Exploit:
        def __reduce__(self):
            return os.system, ("touch " + str(marker),)
    path, output, _ = legacy(tmp_path)
    torch.save({"model_state_dict": {"evil": Exploit()}, "iter": 0}, path)
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    # Unsafe execution may only occur inside the sandbox. Its exit result is
    # plain data; all generated bytes are independently weights-only validated.
    receipt = convert(module, path, output, digest)
    assert receipt["independent_safe_validation"] is True
    assert not marker.exists()


